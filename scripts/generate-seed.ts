// Generates supabase/seed/202610220002_seed_visits.sql from the static site data.
// Run: node scripts/generate-seed.ts > supabase/seed/202610220002_seed_visits.sql
import { programs } from '../src/lib/data/accreditation.ts';

const q = (value: string | number | null | undefined): string =>
	value === null || value === undefined ? 'null' : typeof value === 'number' ? String(value) : `'${value.replace(/'/g, "''")}'`;

const lines: string[] = [];
const out = (line = '') => lines.push(line);

out('-- Seed visits, sections and documents from src/lib/data/accreditation.ts.');
out('-- Generated by scripts/generate-seed.ts. Run after 202610220001_visits.sql.');
out('-- Rows are published, matching what the static site shows today.');
out('');
out('begin;');
out('');

for (const program of programs) {
	out(`-- ${program.code}`);
	out(
		`update public.programs set slug = ${q(program.slug)}, name = ${q(program.name)}, degree = ${q(program.degree)}, summary = ${q(program.summary)},` +
			` theme_program = ${q(program.theme.program)}, theme_ink = ${q(program.theme.ink)}, theme_soft = ${q(program.theme.soft)},` +
			` theme_contrast = ${q(program.theme.contrast)}, sort_order = ${program.sortOrder} where code = ${q(program.code)};`
	);
	out(`do $$ begin if not found then raise exception 'program ${program.code} not found'; end if; end $$;`.replace('if not found', `if not exists (select 1 from public.programs where code = ${q(program.code)})`));
	out('');

	for (const visit of program.visits) {
		out(
			`insert into public.visits (program_id, slug, year, level, label, previous_label, status, workflow, sort_order)` +
				` select id, ${q(visit.slug)}, ${visit.year}, ${q(visit.level)}, ${q(visit.label)}, ${q(visit.previousLabel ?? null)}, ${q(visit.status)}, 'published', 0` +
				` from public.programs where code = ${q(program.code)};`
		);

		visit.sections.forEach((section, sectionIndex) => {
			out(
				`insert into public.areas (visit_id, kind, number, slug, title, short_title, description, focus, sort_order, status)` +
					` select v.id, ${q(section.kind)}, ${q(section.number ?? null)}, ${q(section.slug)}, ${q(section.title)}, ${q(section.shortTitle)},` +
					` ${q(section.description)}, ${q(section.focus ?? null)}, ${sectionIndex}, 'published'` +
					` from public.visits v join public.programs p on p.id = v.program_id where p.code = ${q(program.code)} and v.slug = ${q(visit.slug)};`
			);

			if (section.documents.length === 0) return;
			out(`insert into public.documents (area_id, title, kind, format, drive_url, status, updated_label, note, sort_order, workflow)`);
			out(`select a.id, d.title, d.kind, d.format, d.drive_url, d.status::public.document_status, d.updated_label, d.note, d.sort_order, 'published'`);
			out(`from (values`);
			section.documents.forEach((document, index) => {
				const comma = index === section.documents.length - 1 ? '' : ',';
				out(
					`\t(${q(document.title)}, ${q(document.kind)}, ${q(document.format)}, ${q(document.driveUrl ?? null)}, ${q(document.status)},` +
						` ${q(document.updated ?? null)}, ${q(document.note ?? null)}, ${index})${comma}`
				);
			});
			out(`) as d(title, kind, format, drive_url, status, updated_label, note, sort_order)`);
			out(
				`join public.areas a on a.slug = ${q(section.slug)}` +
					` join public.visits v on v.id = a.visit_id and v.slug = ${q(visit.slug)}` +
					` join public.programs p on p.id = v.program_id and p.code = ${q(program.code)};`
			);
		});
		out('');
	}
}

out('commit;');
console.log(lines.join('\n'));
